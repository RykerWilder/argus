// Export del report email (Markdown per i ticket, JSON completo). Costruiti nel
// browser a partire dal report ricevuto: niente passa di nuovo dal backend.

import type { EmailAddress, EmailReport } from "../types";

export function duration(seconds: number | null | undefined): string | null {
  if (seconds === null || seconds === undefined) return null;
  const s = Math.abs(seconds);
  const sign = seconds < 0 ? "−" : "";
  if (s < 60) return `${sign}${s} s`;
  if (s < 3600) return `${sign}${Math.floor(s / 60)} min ${s % 60 ? `${s % 60} s` : ""}`.trim();
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  return `${sign}${h} h${m ? ` ${m} min` : ""}`;
}

const addr = (a: EmailAddress | null | undefined): string =>
  a ? (a.name ? `${a.name} <${a.address || ""}>` : a.address || "") : "";
const esc = (v: unknown): string => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function defangText(v: string): string {
  return String(v).replace(/\./g, "[.]").replace(/@/g, "[@]").replace(/^http/i, "hxxp");
}

export function emailFileName(report: EmailReport, ext: string): string {
  const subject = (report.summary.subject || "email").replace(/[^a-z0-9]+/gi, "_").slice(0, 40).replace(/^_|_$/g, "");
  return `argus-email-${subject || "message"}-${new Date().toISOString().slice(0, 10)}.${ext}`;
}

export function emailToJSON(report: EmailReport): string {
  return JSON.stringify({ generatedBy: "Argus email header analyzer", generatedAt: new Date().toISOString(), ...report }, null, 2);
}

export function emailToMarkdown(report: EmailReport): string {
  const s = report.summary;
  const a = report.authentication;
  const L: string[] = [];
  L.push(`# Email analysis: ${s.subject || "(no subject)"}`, "");
  L.push(`**Verdict:** ${report.verdict.title}${report.verdict.reasons.length ? ` — ${report.verdict.reasons.join(", ")}` : ""}`, "");
  L.push("| Field | Value |", "| --- | --- |");
  [
    ["From", addr(s.from)],
    ["Reply-To", s.replyTo.map(addr).join(", ")],
    ["Return-Path", addr(s.returnPath)],
    ["To", s.to.map(addr).join(", ")],
    ["Date", s.date],
    ["Message-ID", s.messageId],
    ["Origin IP", report.origin ? report.origin.ip : ""],
    ["Mailer", s.mailer],
  ].forEach(([k, v]) => v && L.push(`| ${k} | ${esc(v)} |`));
  L.push("", "## Authentication (as recorded in the headers)", "");
  for (const key of ["spf", "dkim", "dmarc", "arc", "compauth"] as const) {
    const m = a[key];
    if (m) L.push(`- **${key.toUpperCase()}**: ${m.result}${m.props?.["header.d"] ? ` (d=${m.props["header.d"]})` : ""}${m.props?.["smtp.mailfrom"] ? ` (mailfrom ${m.props["smtp.mailfrom"]})` : ""}${m.props?.["header.from"] ? ` (from ${m.props["header.from"]})` : ""}`);
  }
  if (report.findings.length) {
    L.push("", "## Findings", "");
    report.findings.forEach((f) => L.push(`- [${f.level}] ${f.title}${f.detail ? ` — ${f.detail}` : ""}`));
  }
  if (report.hops.length) {
    L.push("", "## Route", "", "| # | From | IP | By | Protocol | TLS | Time | Delay |", "| --- | --- | --- | --- | --- | --- | --- | --- |");
    report.hops.forEach((h) => {
      const geo = h.from?.ip ? report.geo?.[h.from.ip] : null;
      L.push(`| ${h.index} | ${esc(h.from?.rdns || h.from?.host || "")} | ${esc(h.from?.ip || "")}${geo ? ` (${esc(geo.city || "")}${geo.city ? ", " : ""}${esc(geo.countryCode || "")})` : ""} | ${esc(h.by?.host || "")} | ${esc(h.protocol || "")} | ${h.tls ? h.tlsVersion || "yes" : "no"} | ${esc(h.date || "")} | ${esc(duration(h.delaySeconds) || "")} |`);
    });
  }
  const ind = report.indicators;
  if (ind.ips.length || ind.domains.length || ind.urls.length || report.attachments.length) {
    L.push("", "## Indicators (defanged)", "");
    ind.ips.forEach((i) => L.push(`- IP ${defangText(i.value)} (${i.role})`));
    ind.domains.forEach((d) => L.push(`- Domain ${defangText(d.value)} (${d.role})`));
    ind.emails.forEach((e) => L.push(`- Email ${defangText(e.value)} (${e.role})`));
    ind.urls.forEach((u) => L.push(`- URL ${defangText(u)}`));
    report.attachments.forEach((f) => L.push(`- Attachment ${esc(f.filename)} — SHA-256 ${f.sha256}`));
  }
  L.push("", `_Generated by Argus on ${new Date().toISOString()}. The message itself was not stored._`, "");
  return L.join("\n");
}

export function emailSummaryText(report: EmailReport): string {
  const s = report.summary;
  return [
    `Subject: ${s.subject || "(no subject)"}`,
    `Verdict: ${report.verdict.title}${report.verdict.reasons.length ? ` (${report.verdict.reasons.join(", ")})` : ""}`,
    `From: ${addr(s.from)}`,
    s.replyTo.length ? `Reply-To: ${s.replyTo.map(addr).join(", ")}` : null,
    s.returnPath ? `Return-Path: ${addr(s.returnPath)}` : null,
    report.origin ? `Origin IP: ${report.origin.ip}` : null,
    ...(["spf", "dkim", "dmarc"] as const).map((k) => {
      const m = report.authentication[k];
      return m ? `${k.toUpperCase()}: ${m.result}` : null;
    }),
  ]
    .filter(Boolean)
    .join("\n");
}
